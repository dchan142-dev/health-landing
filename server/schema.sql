CREATE TABLE IF NOT EXISTS hd_record (
 id TEXT PRIMARY KEY,
 user_id TEXT UNIQUE NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
 answers_ciphertext TEXT NOT NULL,
 step INTEGER NOT NULL DEFAULT 0 CHECK (step BETWEEN 0 AND 7),
 version INTEGER NOT NULL DEFAULT 1,
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','submitted')),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 submitted_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS hd_app_access (
  app_key TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS hd_daily (
  user_id TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  day DATE NOT NULL,
  content_ciphertext TEXT NOT NULL,
  version INTEGER NOT NULL DEFAULT 1,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, day)
);
CREATE TABLE IF NOT EXISTS hd_audit (
 id TEXT PRIMARY KEY,actor_id TEXT NOT NULL,action TEXT NOT NULL,record_id TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS hd_daily_preview (
  user_id TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  day DATE NOT NULL,
  content_ciphertext TEXT NOT NULL,
  version INTEGER NOT NULL DEFAULT 1,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, day)
);

CREATE TABLE IF NOT EXISTS hd_photo (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  day DATE NOT NULL,
  meal TEXT NOT NULL CHECK (meal IN ('breakfast','lunch','snack','dinner')),
  kind TEXT NOT NULL CHECK (kind IN ('actual','preview')),
  sha256 TEXT NOT NULL,
  drive_file_id TEXT NOT NULL,
  drive_folder_id TEXT NOT NULL,
  byte_size INTEGER NOT NULL CHECK(byte_size>0),
  verified_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(user_id,day,meal,kind,sha256)
);
