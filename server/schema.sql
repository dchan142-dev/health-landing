CREATE TABLE IF NOT EXISTS hd_record (
 id TEXT PRIMARY KEY,
 user_id TEXT UNIQUE NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
 answers_ciphertext TEXT NOT NULL,
 step INTEGER NOT NULL DEFAULT 0 CHECK (step BETWEEN 0 AND 7),
 version INTEGER NOT NULL DEFAULT 1,
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','submitted')),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 submitted_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS hd_audit (
 id TEXT PRIMARY KEY,actor_id TEXT NOT NULL,action TEXT NOT NULL,record_id TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
